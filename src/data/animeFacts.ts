const norm = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, ' ')

/** Cari grup fakta yang cocok sama salah satu judul anime. */
export function factsFor(titles: (string | null | undefined)[]): AnimeFactGroup | null {
  const hay = titles.filter(Boolean).map((t) => ` ${norm(t!)} `)
  return ANIME_FACTS.find((g) => g.aliases.some((a) => hay.some((h) => h.includes(` ${norm(a)} `)))) ?? null
}

export const ALL_FACTS = ANIME_FACTS.flatMap((g) => g.facts.map((fact) => ({ fact, group: g })))
